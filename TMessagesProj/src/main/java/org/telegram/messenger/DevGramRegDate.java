/*
 * DevGram: примерная дата регистрации по ID (как в exteraGram).
 *
 * Telegram выдаёт пользователям id монотонно по времени, поэтому по id можно оценить,
 * когда аккаунт примерно создан. Точность приблизительная: между реперными точками
 * интерполируем линейно, за краями — экстраполируем по ближайшему отрезку.
 * Реперы — публично известные пары (id, дата), тот же принцип, что у age-ботов.
 */

package org.telegram.messenger;

import java.util.Calendar;

public class DevGramRegDate {

    // Пары: id пользователя -> unix-время (секунды) примерной регистрации.
    // Должны идти по возрастанию id. Верхняя часть откалибрована по реальным замерам.
    private static final long[][] POINTS = {
            {1000000L,       1377993600L}, // 2013-09
            {5000000L,       1379635200L}, // 2013-09
            {10000000L,      1383264000L}, // 2013-11
            {50000000L,      1404172800L}, // 2014-07
            {100000000L,     1433116800L}, // 2015-06
            {150000000L,     1454284800L}, // 2016-02
            {200000000L,     1470009600L}, // 2016-08
            {300000000L,     1483228800L}, // 2017-01
            {400000000L,     1501545600L}, // 2017-08
            {500000000L,     1520899200L}, // 2018-03
            {600000000L,     1538352000L}, // 2018-10
            {700000000L,     1554076800L}, // 2019-04
            {800000000L,     1572566400L}, // 2019-11
            {900000000L,     1588291200L}, // 2020-05
            {1000000000L,    1601510400L}, // 2020-10
            {1200000000L,    1609459200L}, // 2021-01
            {1400000000L,    1617235200L}, // 2021-04
            {1600000000L,    1622505600L}, // 2021-06
            {1800000000L,    1627776000L}, // 2021-08
            {2000000000L,    1633046400L}, // 2021-10
            {2140745658L,    1635724800L}, // 2021-11 — реальная точка (dateregbot)
            {2400000000L,    1640995200L}, // 2022-01
            {2800000000L,    1648771200L}, // 2022-04
            {3200000000L,    1656633600L}, // 2022-07
            {4000000000L,    1672531200L}, // 2023-01
            {5000000000L,    1690848000L}, // 2023-08
            {6000000000L,    1709251200L}, // 2024-03
            {7000000000L,    1727740800L}, // 2024-10
    };

    // Примерное unix-время регистрации, либо 0 если оценить нельзя.
    public static long estimateUnixTime(long userId) {
        if (userId <= 0) {
            return 0;
        }
        long[][] p = POINTS;
        if (userId <= p[0][0]) {
            return interpolate(userId, p[0], p[1]);
        }
        if (userId >= p[p.length - 1][0]) {
            return interpolate(userId, p[p.length - 2], p[p.length - 1]);
        }
        for (int i = 0; i < p.length - 1; i++) {
            if (userId >= p[i][0] && userId <= p[i + 1][0]) {
                return interpolate(userId, p[i], p[i + 1]);
            }
        }
        return 0;
    }

    private static long interpolate(long id, long[] a, long[] b) {
        double k = (double) (id - a[0]) / (double) (b[0] - a[0]);
        return (long) (a[1] + k * (b[1] - a[1]));
    }

    // Предложный падеж: «примерно в <месяце> <год>».
    private static final String[] MONTHS_PREP = {
            "январе", "феврале", "марте", "апреле", "мае", "июне",
            "июле", "августе", "сентябре", "октябре", "ноябре", "декабре"
    };

    // «в ноябре 2021» — месяц и год, без числа (точность не позволяет).
    public static String estimate(long userId) {
        long t = estimateUnixTime(userId);
        if (t <= 0) {
            return null;
        }
        Calendar c = Calendar.getInstance();
        c.setTimeInMillis(t * 1000L);
        return MONTHS_PREP[c.get(Calendar.MONTH)] + " " + c.get(Calendar.YEAR);
    }
}
